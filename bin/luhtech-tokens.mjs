#!/usr/bin/env node
/**
 * Generates tokens.generated.css from a brand-identity.schema.json instance.
 * Moved into @luh-tech/site-template from the per-repo generate-tokens.mjs
 * scripts (Ectropy-Business, LuhTech-Business, Replique, ...) it replaces --
 * same real logic, generalized to take instance/output paths as CLI args
 * instead of assuming one repo's directory layout.
 *
 * Usage:
 *   luhtech-tokens <path-to-brand-identity.json> <output-css-path>
 *   luhtech-tokens content/brand/ectropy.json src/styles/tokens.generated.css
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';

const SCHEMA_BASE = 'https://schemas.luh.tech';
const SCHEMA_REFS = [
  'portfolio/brand-identity.schema.json',
  '_enums/luhtech-enums.schema.v2.json',
  '_enums/venture.enum.json',
  '_definitions/definitions.schema.json',
  '_definitions/graph.schema.json',
];

const [, , instanceArg, outputArg] = process.argv;
if (!instanceArg || !outputArg) {
  console.error('Usage: luhtech-tokens <path-to-brand-identity.json> <output-css-path>');
  process.exit(1);
}
const instancePath = resolve(process.cwd(), instanceArg);
const outputPath = resolve(process.cwd(), outputArg);

async function fetchSchema(rel) {
  const url = `${SCHEMA_BASE}/${rel}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch canonical schema ${url}: HTTP ${res.status}.`);
  }
  return res.json();
}

function readInstance(path) {
  let raw;
  try {
    raw = readFileSync(path, 'utf-8');
  } catch {
    throw new Error(`No brand-identity instance at ${path}.`);
  }
  return JSON.parse(raw);
}

function cssColor(colorValue) {
  return colorValue.oklch;
}

function fontStack(fontRef, fallback) {
  return `"${fontRef.family}", ${fallback}`;
}

function generateCss(brand) {
  const { color, identity, brandId, typography } = brand;
  return `/* GENERATED by luhtech-tokens (@luh-tech/site-template) from ${instanceArg} -- DO NOT HAND-EDIT.
 * Source brand: ${brandId} (${identity.name})
 * Regenerated on every predev/prebuild. Edit the brand-identity JSON instance instead.
 */
@theme {
  --color-ink: ${cssColor(color.foundation.ink)};
  --color-canvas: ${cssColor(color.foundation.canvas)};
  --color-accent-primary: ${cssColor(color.accent.primary)};
${color.accent.secondary ? `  --color-accent-secondary: ${cssColor(color.accent.secondary)};\n` : ''}
  --font-display: ${fontStack(typography.display, 'sans-serif')};
  --font-body: ${fontStack(typography.body, 'sans-serif')};
  --font-mono: ${fontStack(typography.mono, 'monospace')};
}
`;
}

async function main() {
  const ajv = new Ajv({ strict: false, allErrors: true });
  addFormats(ajv);

  const [brandIdentitySchema, ...refs] = await Promise.all(SCHEMA_REFS.map(fetchSchema));
  for (const ref of refs) {
    ajv.addSchema(ref);
  }
  const validate = ajv.compile(brandIdentitySchema);

  const brand = readInstance(instancePath);

  if (!validate(brand)) {
    const detail = (validate.errors ?? [])
      .map((e) => `${e.instancePath || '(root)'}: ${e.message}`)
      .join('; ');
    throw new Error(
      `${instancePath} failed validation against portfolio/brand-identity.schema.json: ${detail}`
    );
  }

  const css = generateCss(brand);
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, css, 'utf-8');
  console.log(`Generated ${outputPath} from ${instancePath} (brandId: ${brand.brandId})`);
}

main().catch((err) => {
  console.error(`luhtech-tokens failed: ${err.message}`);
  process.exit(1);
});
