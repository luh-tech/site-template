#!/usr/bin/env node
/**
 * Pulls each venture's real display name + oneLiner from its own canonical
 * content/brand/{id}.json (schema: portfolio/brand-identity.schema.json,
 * identity.name / identity.oneLiner) into this package's generated venture
 * directory, consumed by VentureCard.astro -- so a card showing a sibling
 * venture renders its real display name (e.g. "JobsiteControl") instead of
 * the raw brandRef slug (e.g. "jobsitecontrol") a crossLink carries.
 *
 * Local dev-time tool only -- reads sibling repo checkouts on disk, same
 * as the other luhtech-sync-* tools, so it can't run in CI. Regenerates
 * src/lib/venture-directory.generated.ts entirely on every run (it's
 * generated output, never hand-edited).
 *
 * Usage:
 *   luhtech-sync-venture-directory [--dev-root <path>]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { VENTURES } from './lib/ventures.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REGISTRY_PATH = join(__dirname, '..', 'src', 'lib', 'venture-directory.generated.ts');

const args = process.argv.slice(2);
const devRootFlagIdx = args.indexOf('--dev-root');
const devRoot = devRootFlagIdx >= 0 ? args[devRootFlagIdx + 1] : join(homedir(), 'dev', 'luhtech');

function main() {
  const found = [];
  const skipped = [];

  for (const v of VENTURES) {
    if (!v.brandJson) {
      skipped.push(`${v.id}: no brandJson path configured`);
      continue;
    }
    const srcPath = join(devRoot, v.repo, v.brandJson);
    if (!existsSync(srcPath)) {
      skipped.push(`${v.id}: no brand.json at ${srcPath}`);
      continue;
    }
    let brand;
    try {
      brand = JSON.parse(readFileSync(srcPath, 'utf-8'));
    } catch (e) {
      skipped.push(`${v.id}: ${srcPath} is not valid JSON (${e.message})`);
      continue;
    }
    const name = brand?.identity?.name;
    const oneLiner = brand?.identity?.oneLiner;
    if (!name || !oneLiner) {
      skipped.push(`${v.id}: ${srcPath} missing identity.name or identity.oneLiner`);
      continue;
    }
    found.push({ id: v.id, name, oneLiner });
    console.log(`  + ${v.id}: "${name}" from ${srcPath}`);
  }

  const entries = found
    .map((f) => `  ${f.id}: ${JSON.stringify({ name: f.name, oneLiner: f.oneLiner })},`)
    .join('\n');

  const output = `// GENERATED by bin/luhtech-sync-venture-directory.mjs -- DO NOT HAND-EDIT.
// Regenerate with \`luhtech-sync-venture-directory\` (reads each venture's own
// content/brand/{id}.json identity.name / identity.oneLiner from its
// sibling repo checkout on disk). A venture with no entry here falls back
// to its raw brandRef slug in VentureCard.astro.
export interface VentureDirectoryEntry {
\tname: string;
\toneLiner: string;
}

export const VENTURE_DIRECTORY: Record<string, VentureDirectoryEntry> = {
${entries}
};
`;

  writeFileSync(REGISTRY_PATH, output, 'utf-8');
  console.log(`\n${found.length} venture(s) pulled, ${skipped.length} skipped:`);
  skipped.forEach((s) => console.log(`  - ${s}`));
  console.log(`\nWrote ${REGISTRY_PATH}`);
}

main();
